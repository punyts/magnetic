const ALL: Record<Language, Texts> = { en: EN, de: DE, fr: FR, es: ES };

/** Every text of a language */
export function textsOf(language: Language): Texts {
    return ALL[language];
}

/** A text with its `{name}` marks filled; a mark with no value stays as it is */
export function fill(text: string, values: Record<string, string | number> = {}): string {
    return text.replace(/\{(\w+)\}/g, (mark, name: string) => (values[name] === undefined ? mark : String(values[name])));
}

/**
 * The texts a page's scripts read, as a JSON script block (`#magnetic-text`), never run. `<` is escaped so no text can
 * close the block
 */
export function textBlock(language: Language): string {
    return `<script type="application/json" id="magnetic-text">${JSON.stringify(ALL[language]).replace(/</g, '\\u003c')}</script>`;
}

